"""make_names.py FONT OUT.inc -- the Extra heroes' names for their upgrade
pictures, drawn once with a free font (TeX Gyre Pagella Bold, GUST licence)
and kept as two 8-bit masks each: the letters and their dark outline."""
import sys
from PIL import Image, ImageDraw, ImageFont, ImageFilter
font = ImageFont.truetype(sys.argv[1], 38)
out = open(sys.argv[2], 'w')
out.write('/* generated by tools/names/make_names.py -- do not edit */\n')
names = ['Boromir', 'Gandalf', 'Frodo', 'Lurtz', 'Elrond', 'Sauron', 'Uruk-hai', 'Saruman']
for n in names:
    l, t, r, b = font.getbbox(n)
    W, H = r - l + 12, b - t + 12
    fill = Image.new('L', (W, H)); ImageDraw.Draw(fill).text((6 - l, 6 - t), n, font=font, fill=255)
    edge = fill.filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.GaussianBlur(1.2))
    out.write('static const uint8_t s_name_%s_fill[%d] = {' % (n.lower().replace('-',''), W * H))
    out.write(','.join(str(v) for v in fill.getdata()) + '};\n')
    out.write('static const uint8_t s_name_%s_edge[%d] = {' % (n.lower().replace('-',''), W * H))
    out.write(','.join(str(v) for v in edge.getdata()) + '};\n')
    out.write('#define NAME_%s_W %d\n#define NAME_%s_H %d\n' % (n.upper().replace('-',''), W, n.upper().replace('-',''), H))
